def nav_current(html, href):
    html = html.replace(' aria-current="page"', '')
    return html.replace(f'<a href="{href}">', f'<a href="{href}" aria-current="page">', 1)


def page(slug, title, desc, eyebrow, h1, lede, body, current):
    out = HEAD.format(
        title=title, desc=desc, eyebrow=eyebrow, h1=h1, lede=lede,
        header=nav_current(header, current), footer=footer, body=body,
    )
    (ROOT / slug).write_text(out, encoding='utf-8')
    print('written', slug)


